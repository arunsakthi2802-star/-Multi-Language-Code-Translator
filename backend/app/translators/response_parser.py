import json
import re
from typing import Dict, Any, List

class TranslationResponseParser:
    @staticmethod
    def parse(response_text: str, default_source: str, default_target: str) -> Dict[str, Any]:
        """
        Safely extracts and validates structured translation payload.
        Handles ```json ``` markdown wrappers and stray text.
        """
        cleaned = response_text.strip()
        
        # Strip markdown code fence if present
        if cleaned.startswith("```"):
            lines = cleaned.split("\n")
            if lines[0].startswith("```"):
                lines = lines[1:]
            if lines and lines[-1].strip() == "```":
                lines = lines[:-1]
            cleaned = "\n".join(lines).strip()

        try:
            data = json.loads(cleaned)
            if isinstance(data, dict):
                return {
                    "source_language": data.get("source_language", default_source),
                    "target_language": data.get("target_language", default_target),
                    "translated_code": data.get("translated_code", "").strip(),
                    "explanation": data.get("explanation", ""),
                    "conversion_notes": data.get("conversion_notes", []),
                    "warnings": data.get("warnings", []),
                    "suggested_tests": data.get("suggested_tests", [])
                }
        except json.JSONDecodeError:
            pass

        # Fallback: regex search for JSON block
        json_pattern = re.search(r"(\{[\s\S]*\})", response_text)
        if json_pattern:
            try:
                data = json.loads(json_pattern.group(1))
                if isinstance(data, dict) and "translated_code" in data:
                    return {
                        "source_language": data.get("source_language", default_source),
                        "target_language": data.get("target_language", default_target),
                        "translated_code": data.get("translated_code", "").strip(),
                        "explanation": data.get("explanation", ""),
                        "conversion_notes": data.get("conversion_notes", []),
                        "warnings": data.get("warnings", []),
                        "suggested_tests": data.get("suggested_tests", [])
                    }
            except Exception:
                pass

        # If raw code returned directly
        # Check if code block in response
        code_block = re.search(r"```(?:[a-zA-Z0-9_\-]+)?\n([\s\S]*?)```", response_text)
        if code_block:
            code = code_block.group(1).strip()
        else:
            code = response_text.strip()

        return {
            "source_language": default_source,
            "target_language": default_target,
            "translated_code": code,
            "explanation": "Translated code generated by AI provider.",
            "conversion_notes": ["Direct code output was returned without structured JSON envelope."],
            "warnings": ["Model output was parsed with fallback extractor."],
            "suggested_tests": []
        }
